DROP TABLE IF EXISTS compras;
DROP TABLE IF EXISTS catalogo;
DROP TABLE IF EXISTS clientes;

-- ---------------------------------------------------------------------
-- Tablas
-- ---------------------------------------------------------------------

CREATE TABLE clientes (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre    VARCHAR(100) NOT NULL,
  apellido  VARCHAR(100) NOT NULL,
  cedula    VARCHAR(20)  NOT NULL UNIQUE,
  telefono  VARCHAR(20)  NOT NULL,
  sexo      VARCHAR(20)  NOT NULL
);

CREATE TABLE catalogo (
  id_vehiculo  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  marca        VARCHAR(50)  NOT NULL,
  modelo       VARCHAR(50)  NOT NULL,
  anio         INTEGER      NOT NULL,
  cc           INTEGER      NOT NULL,
  precio       BIGINT       NOT NULL,
  categoria    VARCHAR(20)  NOT NULL
);

CREATE TABLE compras (
  id_compra    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente   INTEGER      NOT NULL REFERENCES clientes (id) ON DELETE RESTRICT,
  cliente      VARCHAR(200) NOT NULL,
  cedula       VARCHAR(20)  NOT NULL,
  id_vehiculo  INTEGER      NOT NULL REFERENCES catalogo (id_vehiculo) ON DELETE RESTRICT,
  vehiculo     VARCHAR(100) NOT NULL,
  fecha        DATE         NOT NULL,
  precio       BIGINT       NOT NULL,
  estado       VARCHAR(20)  NOT NULL
);

CREATE INDEX idx_compras_id_cliente  ON compras (id_cliente);
CREATE INDEX idx_compras_id_vehiculo ON compras (id_vehiculo);

